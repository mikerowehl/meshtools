import sys
import time

import meshtastic.tcp_interface
from pubsub import pub

my_num = None


def describe(packet):
    # Fields that are zero/unset are left out of the dict entirely, hence .get() everywhere.
    num = packet.get("from", 0)
    sender = packet.get("fromId") or f"!{num:08x}(unknown)"

    if "decoded" in packet:
        what = packet["decoded"].get("portnum", "?")
    elif "encrypted" in packet:
        what = "ENCRYPTED(no key)"
    else:
        what = "?"

    if num == my_num:
        return f"{sender} {what} [local: generated by my radio, not received over the air]"

    hs, hl = packet.get("hopStart"), packet.get("hopLimit", 0)
    hops = (hs - hl) if hs is not None else "?"
    relay = packet.get("relayNode")
    relay = f"..{relay:02x}" if relay else "-"
    return (f"{sender} {what} snr {packet.get('rxSnr', 0)} rssi {packet.get('rxRssi', '?')} "
            f"hops {hops} relay {relay} ch {packet.get('channel', 0)}")


def on_rx(packet, interface):
    print(describe(packet), flush=True)


if len(sys.argv) != 2:
    sys.exit(f"usage: {sys.argv[0]} RADIO_IP")

pub.subscribe(on_rx, "meshtastic.receive")
iface = meshtastic.tcp_interface.TCPInterface(hostname=sys.argv[1])
my_num = iface.myInfo.my_node_num
print(f"connected to !{my_num:08x}, {len(iface.nodes or {})} nodes in db; listening (Ctrl-C to stop)")
try:
    while True:
        time.sleep(60)
except KeyboardInterrupt:
    iface.close()
